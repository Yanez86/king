def png_size(path):
    w, h = struct.unpack(">II", (ROOT / path).read_bytes()[16:24])
    return w, h


class Sprites:
    """Icone ritagliate dai PNG del gioco: ogni file una volta sola nella pagina (una classe CSS), le icone sono
    riquadri del file. Alte `height` px (16 nel testo, 32 nei titoli): da 8 a 32 sono raddoppi e dimezzamenti."""

    def __init__(self):
        self.files = {}  # file -> classe CSS

    def icon(self, path, x=0, y=0, w=0, h=0, height=16):
        pw, ph = png_size(path)
        w, h = (w, h) if w else (pw, ph)
        self.files.setdefault(path, f"s{len(self.files)}")
        k = height / 16 * (2 if h <= 8 else 0.5 if h > 16 else 1)
        return (f'<i class="sp {self.files[path]}" style="width:{w * k:g}px;height:{h * k:g}px;'
                f'background-position:{-x * k:g}px {-y * k:g}px;background-size:{pw * k:g}px {ph * k:g}px"></i>')

    def css(self):
        return "\n".join(f".{c} {{ background-image: url(data:image/png;base64,"
                         f"{base64.b64encode((ROOT / f).read_bytes()).decode()}); }}" for f, c in self.files.items())


def capitalize(key):
    return " ".join(w.capitalize() for w in key.split("_"))


