def plain(name):
    """per confrontare i nomi: minuscoli, col trattino come spazio (Fun-loving e Fun Loving)"""
    return name.lower().replace("-", " ")


def decorate(text, cat, after=()):
    """l'icona davanti a un testo che è il nome di una cosa del gioco, o che comincia col nome seguito da uno dei
    pezzi di `after` (le voci "Nome: ...", "Nome (...)"); non le intestazioni colorate, né se c'è già un'icona"""
    if text.startswith(("<i ", "<span")):
        return text
    low = plain(text)
    for name, ic in cat.items():
        if low == name or (low.startswith(name) and low[len(name):].startswith(after) and after):
            return f"{ic} {text}"
    return text


def inline(s, sprites):
    s = re.sub(r"\[img=\w+\]res://(.+?)\[/img\]", lambda m: sprites.icon(m.group(1)), s)
    return re.sub(r"\[color=(#\w+)\](.*?)\[/color\]", r'<span style="color:\1">\2</span>', s)


def table(m, sprites, cat):
    cols = int(m.group(1))
    # la prima colonna anche col nome seguito da altro ("Letto (2×1)"), le altre solo col nome intero
    cells = [decorate(inline(c, sprites), cat, (" ", ",", ":") if i % cols == 0 else ())
             for i, c in enumerate(re.findall(r"\[cell\](.*?)\[/cell\]", m.group(2), re.S))]
    rows = ["<tr>" + "".join(f"<td>{c}</td>" for c in cells[i:i + cols]) + "</tr>" for i in range(0, len(cells), cols)]
    return "\x00<table>" + "".join(rows) + "</table>\n"


def page(text, sprites, cat):
    inline_ = lambda s: inline(s, sprites)
    text = re.sub(r"\[table=(\d+)\](.*?)\[/table\]\n?", lambda m: table(m, sprites, cat), html.escape(text, quote=False),
                  flags=re.S)
    out, in_list = [], False
    for line in text.split("\n"):
        line = line.strip()
        bullet = line.startswith("•")
        if in_list and not bullet:
            out.append("</ul>")
            in_list = False
        if not line:
            continue
        if line.startswith("\x00"):
            out.append(line[1:])
        elif bullet:
            if not in_list:
                out.append("<ul>")
                in_list = True
            out.append(f"<li>{decorate(inline_(line[1:].strip()), cat, (':', ' ('))}</li>")
        elif m := re.fullmatch(r"\[color=(#\w+)\](.*?)\[/color\]\s*((?:\[img=.*?\[/img\]\s*)*)", line):
            tag = "h3" if m.group(1) == HEADING else "h4"
            out.append(f"<{tag}>{inline_(m.group(2))} {inline_(m.group(3))}</{tag}>")
        else:
            out.append(f"<p>{inline_(line)}</p>")
    return "\n".join(out + (["</ul>"] if in_list else []))


def wiki_pages(path):
    src = (ROOT / path).read_text()
    return re.findall(r'^\t\["(.+?)", """(.*?)"""\],', src, re.M | re.S)


def split_comment(line):
    """(codice, commento): il primo # fuori dalle virgolette."""
    quote = None
    for i, ch in enumerate(line):
        if quote:
            if ch == "\\":
                continue
            if ch == quote and line[i - 1] != "\\":
                quote = None
        elif ch in "\"'":
            quote = ch
        elif ch == "#":
            return line[:i], line[i:]
    return line, ""


def depth(code):
    code = re.sub(r'"(?:\\.|[^"\\])*"', "", code)
    return sum(code.count(c) for c in "([{") - sum(code.count(c) for c in ")]}")


def kept(unit):
    """Via shader e costanti solo grafiche: quelle in cui ogni valore è un preload o un colore (GEAR, con una tinta, resta)."""
    if unit[0].startswith("enum"):
        return True
    if '"""' in unit[0]:
        return False
    code = [split_comment(unit[0])[0].split("=", 1)[-1]] + [split_comment(l)[0] for l in unit[1:]]
    code = [c for c in code if c.strip().strip("{[()]}")]
    return not all("preload(" in c or "Color" in c for c in code)


def blocks(path):
    """Gruppi (commento + costanti che lo seguono, o righe vuote a separarli) della parte in cima al file, con le sole costanti ed enum utili."""
    lines = (ROOT / path).read_text().split("\n")
    end = next(i for i, l in enumerate(lines) if re.match(r"(func|class|var|@onready) ", l))
    groups, cur, i = [], [], 0
    while i < end:
        line = lines[i]
        if not line.strip():
            groups.append(cur)
            cur, i = [], i + 1
            continue
        if not re.match(r"(const|enum) ", line):
            if line.startswith("#"):
                if cur and cur[-1][0] == "decl":  # un commento dopo delle costanti apre un nuovo gruppo
                    groups.append(cur)
                    cur = []
                cur.append(("comment", [line]))
            i += 1
            continue
        unit, d, triple = [line], depth(split_comment(line)[0]), line.count('"""') % 2
        while (d > 0 or triple) and i + 1 < end:
            i += 1
            unit.append(lines[i])
            triple ^= lines[i].count('"""') % 2
            d += depth(split_comment(lines[i])[0])
        cur.append(("decl", unit))
        i += 1
    groups.append(cur)
    return [g for g in groups if any(k == "decl" and kept(u) for k, u in g)]


def code_line(line):
    code, comment = (html.escape(p, quote=False) for p in split_comment(line))
    code = re.sub(r"^(const|enum) (\w+)", r'\1 <b id="c-\2">\2</b>', code)
    return code + (f"<i>{comment}</i>" if comment else "")


def numbers(path):
    out = []
    for g in blocks(path):
        rows = [code_line(l) for k, u in g if k == "comment" or kept(u) for l in u]
        out.append("<pre>" + "\n".join(rows) + "</pre>")
    return "\n".join(out)


def slug(s):
    return re.sub(r"\W+", "-", s.lower()).strip("-")


