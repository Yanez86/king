def md(s):
    """markdown in linea del GDD -> html"""
    s = html.escape(s.strip(), quote=False)
    s = re.sub(r"\*\*(.+?)\*\*", r"<b>\1</b>", s)
    s = re.sub(r"(?<![\w*])\*(?=\S)(.+?)\*", r"<em>\1</em>", s)
    return re.sub(r"`(.+?)`", r"<code>\1</code>", s)


def gdd_blocks():
    """[(titolo della sezione, testo)]: i paragrafi e le voci del GDD, con le righe che continuano unite (non le tabelle)"""
    out, title, cur = [], "", None
    for line in (ROOT / "docs" / "GDD.md").read_text().split("\n"):
        if m := re.match(r"#+\s+(.*)", line):
            title, cur = m.group(1), None
        elif not line.strip() or line.lstrip().startswith("|"):
            cur = None
        elif cur is None or re.match(r"\s*(- |\*\*|\d+\. )", line):
            cur = [title, line.strip()]
            out.append(cur)
        else:
            cur[1] += " " + line.strip()
    return out


def gdd_table(header):
    """le righe della tabella del GDD che comincia con `header`; una prima cella vuota ripete quella di sopra"""
    lines = [l.strip() for l in (ROOT / "docs" / "GDD.md").read_text().split("\n")]
    i = next(i for i, l in enumerate(lines) if l.startswith(header))
    rows, first = [], ""
    for line in lines[i + 2:]:
        if not line.startswith("|"):
            break
        cells = [c.strip() for c in line.strip("|").split("|")]
        first = cells[0] or first
        rows.append([first] + cells[1:])
    return rows


def phases(blocks):
    """le fasi degli "Ordine di lavoro" che lo "Stato" dopo non dà per fatte: [(sezione, [(n, testo, in parte)])]"""
    heads = {t.split(" ")[0]: t for t, _ in blocks if re.match(r"[\d.]+ ", t)}
    out = []
    for i, (title, text) in enumerate(blocks):
        m = re.match(r"(?:- )?\*\*Ordine di lavoro\*\*\s*(?:\(([\d.]+)[^)]*\))?:\s*(.*)", text)
        if not m:
            continue
        steps = re.findall(r"\((\d+)\)\s*(.*?)(?=;?\s*\(\d+\)\s|$)", m.group(2))
        state = next((t for _, t in blocks[i + 1:i + 3] if "**Stato**" in t), "")
        done = set()
        if f := re.search(r"fatte le fasi ([\d–, e-]+)", state):
            for a, b in re.findall(r"(\d+)(?:[–-](\d+))?", f.group(1)):
                done.update(range(int(a), int(b or a) + 1))
        part = {int(n) for n in re.findall(r"della (\d+)", state)}
        out.append((heads.get(m.group(1), title), [(int(n), t.rstrip(".;"), int(n) in part) for n, t in steps
                                                     if int(n) not in done]))
    return out


def roadmap(lang, sprites, cat):
    """la sezione Da sviluppare: fasi non fatte, i "Poi:", ricerche e leggi senza ✓ (il testo è quello del GDD)"""
    w = TODO_WORDS[lang]
    blocks = gdd_blocks()
    out = [f"<h3>{w[0]}</h3>"]
    for head, todo in phases(blocks):
        if todo:
            out.append(f"<h4>{md(head)}</h4><ul>" + "".join(
                f"<li>({n}) {md(t)}" + (f" <small>({w[4]})</small>" if part else "") + "</li>" for n, t, part in todo)
                + "</ul>")
    out.append(f"<h3>{w[1]}</h3>")
    later = {}
    for title, text in blocks:
        for m in re.finditer(r"\bPoi: (.*)", text):
            later.setdefault(title, []).append(m.group(1))
    for title, items in later.items():
        out.append(f"<h4>{md(title)}</h4><ul>" + "".join(f"<li>{md(t)}</li>" for t in items) + "</ul>")
    out.append(f"<h3>{w[2]}</h3>")
    branches = {}
    for branch, name, tier, cost, needs, unlocks in gdd_table("| Ramo | Ricerca |"):
        if "✓" not in name:
            branches.setdefault(branch, []).append(f"<li><b>{md(name)}</b> ({tier}, {cost} {w[6]}"
                                                   + (f"; {w[5]} {md(needs)}" if needs not in ("", "—") else "")
                                                   + f"): {md(unlocks)}</li>")
    for branch, items in branches.items():
        out.append(f"<h4>{decorate(md(branch), cat)}</h4><ul>" + "".join(items) + "</ul>")
    out.append(f"<h3>{w[3]}</h3>")
    kinds = {}
    for kind, name, tier, cost, group, effect, mood in gdd_table("| Categoria | Legge |"):
        if "✓" not in name:
            kinds.setdefault(kind, []).append(f"<li><b>{md(name)}</b> ({tier}" + (f", {cost}" if cost not in ("", "—") else "")
                                              + (f"; {md(group)}" if group not in ("", "—") else "")
                                              + f"): {md(effect)}" + (f" — {w[7]}: {md(mood)}" if mood not in ("", "—") else "")
                                              + "</li>")
    for kind, items in kinds.items():
        out.append(f"<h4>{md(kind)}</h4><ul>" + "".join(items) + "</ul>")
    return "\n".join(out)


def main():
    commit = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, capture_output=True, text=True).stdout.strip()
    for lang, (name, src, words) in LANGS.items():
        pages = wiki_pages(src)
        sprites = Sprites()
        cat = catalog(lang, sprites)
        icons = [sprites.icon(*spec) for spec in PAGE_ICONS] + [""] * len(pages)
        big = [sprites.icon(*spec, height=32) for spec in PAGE_ICONS] + [""] * len(pages)  # nei titoli
        todo_icon = sprites.icon(*TODO_ICON)
        other = next(n for l, (n, _, _) in LANGS.items() if l != lang)
        nav = "".join(f'<a href="#{slug(t)}">{icons[i]} {html.escape(t)}</a>' for i, (t, _) in enumerate(pages))
        nav += f'<h2>{words["dev"]}</h2><a href="#todo">{todo_icon} {words["todo"]}</a>'
        nav += f'<h2>{words["numbers"]}</h2>' + "".join(f'<a href="#{slug(f)}">{f}</a>' for f in NUMBERS)
        body = "".join(f'<section id="{slug(t)}"><h2>{big[i]} {html.escape(t)}</h2>{page(txt, sprites, cat)}</section>'
                       for i, (t, txt) in enumerate(pages))
        body += (f'<section id="todo"><h2>{sprites.icon(*TODO_ICON, height=32)} {words["todo"]}</h2><p class="note">{words["todo_note"]}</p>'
                 f'{roadmap(lang, sprites, catalog("it", sprites))}</section>')
        body += "".join(f'<section id="{slug(f)}"><h2>{words["numbers"]}: {f}</h2>{numbers(f)}</section>' for f in NUMBERS)
        out = ROOT / "docs" / name
        out.write_text(TEMPLATE.format(lang=lang, nav=nav, body=body, commit=commit, date=datetime.date.today().isoformat(),
                                       title=words["title"], note=words["note"].format(src=src), other=other,
                                       other_name=words["other"], sprites=sprites.css()))
        print(f"{out.relative_to(ROOT)}: {len(pages)} pagine, {len(cat)} icone, {out.stat().st_size // 1024} KB")


